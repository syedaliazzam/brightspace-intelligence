function buildCriteria(labels, language = "ur") {
  return labels.map((label, index) => ({
    key: `${language}-${index + 1}`,
    order: index + 1,
    label_en: language === "en" ? label : "",
    label_ur: language === "ur" ? label : "",
    language,
  }));
}

